// Creates .env with fresh random secrets. Never overwrites an existing file.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, '.env');
const arg = (n, d) => { const i = process.argv.indexOf(`--${n}`); return i > 0 ? process.argv[i + 1] : d; };
if (fs.existsSync(target)) { console.log('.env already exists - left untouched.'); process.exit(0); }
const pw = arg('db-password', crypto.randomBytes(18).toString('hex'));
const lines = [
  '# Generated by scripts/gen-env.js - keep this file private (chmod 600). Back up MASTER_KEY: encrypted data cannot be recovered without it.',
  'NODE_ENV=production', `HOST=${arg('host', '127.0.0.1')}`, `PORT=${arg('port', '8080')}`,
  `DATABASE_URL=postgres://nabd:${pw}@127.0.0.1:${arg('db-port', '5432')}/nabd`, `REDIS_URL=redis://127.0.0.1:${arg('redis-port', '6379')}`,
  `MASTER_KEY=${crypto.randomBytes(32).toString('base64')}`, 'COOKIE_SECURE=auto', 'LOG_LEVEL=info', 'AUTO_MIGRATE=true', 'EMBED_WORKER=false', '',
];
fs.writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.log('Created .env');
